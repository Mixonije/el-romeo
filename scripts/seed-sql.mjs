// Writes migrations/0002_seed_services.sql from the starting price list in src/config.js.
//   node scripts/seed-sql.mjs
import { writeFileSync } from 'node:fs';
import config from '../src/config.js';

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const rows = config.seedServices.map((s, i) => `(${[
  q(s.category || 'other'), q(s.name_de), q(s.name_en), q(s.desc_de || null), q(s.desc_en || null),
  q(s.duration_min), q(s.price), q(s.price_from ? 1 : 0), q(i),
].join(', ')})`);
const sql = `-- Starting price list (generated by scripts/seed-sql.mjs). Only runs once, on an empty table.
INSERT INTO services (category, name_de, name_en, desc_de, desc_en, duration_min, price, price_from, sort)
SELECT * FROM (VALUES
  ${rows.join(',\n  ')}
) WHERE NOT EXISTS (SELECT 1 FROM services);
`;
writeFileSync(new URL('../migrations/0002_seed_services.sql', import.meta.url), sql);
console.log(`wrote ${rows.length} services`);
